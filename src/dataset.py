class BrainMRIDataset(Dataset):
    """
    Custom PyTorch Dataset for Brain MRI images.
    Loads images on-demand, ensures 3-channel RGB conversion,
    and applies designated transformations.
    """

    def __init__(self, samples: List[Tuple[Path, int]], transform=None):
        self.samples = samples
        self.transform = transform

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int, str]:
        img_path, label = self.samples[idx]

        with Image.open(img_path) as img:
            rgb_img = img.convert("RGB")

        if self.transform is not None:
            image_tensor = self.transform(rgb_img)
        else:
            image_tensor = rgb_img

        return image_tensor, label, img_path.name


class KerasMRIDataset(utils.PyDataset):
    """
    Keras 3 PyDataset for efficient, thread-safe batch generation.
    Supports in-memory caching of decoded images to accelerate training epochs,
    applying dynamic conservative data augmentations per batch.
    """

    def __init__(
        self,
        samples: List[Tuple[Path, int]],
        batch_size: int = BATCH_SIZE,
        is_training: bool = False,
        preload: bool = True,
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.samples = samples
        self.batch_size = batch_size
        self.is_training = is_training
        self.transform = get_pil_train_augmentation() if is_training else get_pil_eval_preprocessing()
        self.indices = np.arange(len(self.samples))

        # Preload PIL images into memory for maximum training throughput
        self.preload = preload
        self.cached_images = []
        if self.preload:
            for img_path, _ in self.samples:
                with Image.open(img_path) as img:
                    self.cached_images.append(img.convert("RGB"))

        if self.is_training:
            np.random.shuffle(self.indices)

    def __len__(self) -> int:
        return int(np.ceil(len(self.samples) / self.batch_size))

    def __getitem__(self, idx: int) -> Tuple[np.ndarray, np.ndarray]:
        batch_indices = self.indices[idx * self.batch_size : (idx + 1) * self.batch_size]
        batch_images = []
        batch_labels = []

        for i in batch_indices:
            path, label = self.samples[i]
            if self.preload:
                img = self.cached_images[i]
            else:
                with Image.open(path) as raw_img:
                    img = raw_img.convert("RGB")

            # Apply PIL-level transformations
            processed_img = self.transform(img)
            img_arr = np.array(processed_img, dtype=np.float32)

            batch_images.append(img_arr)
            batch_labels.append(label)

        return np.array(batch_images, dtype=np.float32), np.array(batch_labels, dtype=np.int64)

    def get_filenames_in_order(self) -> List[str]:
        """Returns the filenames for all samples in the exact order generated by __getitem__."""
        return [self.samples[i][0].name for i in self.indices]

    def get_filepaths_in_order(self) -> List[Path]:
        """Returns the file paths for all samples in the exact order generated by __getitem__."""
        return [self.samples[i][0] for i in self.indices]

    def on_epoch_end(self):
        """Shuffle indices after each training epoch."""
        if self.is_training:
            np.random.shuffle(self.indices)


def collect_samples(split_dir: Path) -> List[Tuple[Path, int]]:
    """Collects image paths and numeric class IDs."""
    samples = []
    for cls_name in CLASSES:
        cls_dir = split_dir / cls_name
        if not cls_dir.is_dir():
            raise FileNotFoundError(f"Expected class directory not found: {cls_dir}")

        class_id = LABEL2ID[cls_name]
        valid_files = sorted([
            f for f in cls_dir.iterdir()
            if f.is_file() and f.suffix.lower() == ".jpg"
        ])
        for f in valid_files:
            samples.append((f, class_id))

    return samples


def create_splits(
    seed: int = RANDOM_SEED,
    val_ratio: float = VAL_SPLIT_RATIO,
) -> Tuple[List[Tuple[Path, int]], List[Tuple[Path, int]], List[Tuple[Path, int]]]:
    """Creates reproducible, stratified train/validation splits."""
    all_train_samples = collect_samples(TRAIN_DATA_DIR)
    train_paths = [s[0] for s in all_train_samples]
    train_labels = [s[1] for s in all_train_samples]

    train_paths_split, val_paths_split, train_labels_split, val_labels_split = train_test_split(
        train_paths,
        train_labels,
        test_size=val_ratio,
        random_state=seed,
        stratify=train_labels,
        shuffle=True,
    )

    train_samples = list(zip(train_paths_split, train_labels_split))
    val_samples = list(zip(val_paths_split, val_labels_split))
    test_samples = collect_samples(TEST_DATA_DIR)

    return train_samples, val_samples, test_samples


def get_split_statistics(
    train_samples: List[Tuple[Path, int]],
    val_samples: List[Tuple[Path, int]],
    test_samples: List[Tuple[Path, int]],
) -> Dict[str, Any]:
    """Calculates detailed statistics for all splits."""
    stats = {
        "random_seed": RANDOM_SEED,
        "label_mapping": LABEL2ID,
        "input_shape": [3, IMAGE_SIZE[0], IMAGE_SIZE[1]],
        "splits": {},
    }

    split_dict = {
        "train": train_samples,
        "validation": val_samples,
        "test": test_samples,
    }

    for split_name, samples in split_dict.items():
        total = len(samples)
        class_counts = {cls: 0 for cls in CLASSES}
        for _, label_id in samples:
            class_name = ID2LABEL[label_id]
            class_counts[class_name] += 1

        stats["splits"][split_name] = {
            "total_samples": total,
            "class_counts": class_counts,
            "class_distribution_percent": {
                cls: (cnt / total * 100) if total > 0 else 0
                for cls, cnt in class_counts.items()
            },
        }

    return stats


def save_metadata(stats: Dict[str, Any], output_path: Path = RESULTS_DIR / "dataset_metadata.json"):
    """Saves dataset metadata as JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(stats, f, indent=4)


def get_data_loaders(
    batch_size: int = BATCH_SIZE,
    num_workers: int = NUM_WORKERS,
    seed: int = RANDOM_SEED,
) -> Tuple[DataLoader, DataLoader, DataLoader, Dict[str, Any]]:
    """Factory function for PyTorch DataLoaders."""
    train_samples, val_samples, test_samples = create_splits(seed=seed)
    stats = get_split_statistics(train_samples, val_samples, test_samples)
    save_metadata(stats)

    train_dataset = BrainMRIDataset(train_samples, transform=get_train_transforms())
    val_dataset = BrainMRIDataset(val_samples, transform=get_eval_transforms())
    test_dataset = BrainMRIDataset(test_samples, transform=get_eval_transforms())

    pin_memory = torch.cuda.is_available()

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )

    return train_loader, val_loader, test_loader, stats


def get_keras_datasets(
    batch_size: int = BATCH_SIZE,
    seed: int = RANDOM_SEED,
    preload: bool = True,
) -> Tuple[KerasMRIDataset, KerasMRIDataset, KerasMRIDataset, Dict[str, Any]]:
    """Factory function returning Keras 3 PyDatasets for Train, Validation, and Test."""
    train_samples, val_samples, test_samples = create_splits(seed=seed)
    stats = get_split_statistics(train_samples, val_samples, test_samples)
    save_metadata(stats)

    train_ds = KerasMRIDataset(train_samples, batch_size=batch_size, is_training=True, preload=preload)
    val_ds = KerasMRIDataset(val_samples, batch_size=batch_size, is_training=False, preload=preload)
    test_ds = KerasMRIDataset(test_samples, batch_size=batch_size, is_training=False, preload=preload)

    return train_ds, val_ds, test_ds, stats
